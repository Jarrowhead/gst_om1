"""Rule 88A interactive set-off matrix + PMT-06 challan summary (task 11.3).

PHASE11_13_RECOMMENDATION_BUILD.md rec 3: the returns router computes GSTR-3B
liability + ITC but has no set-off-order matrix and no challan summary. This
module adds the statutory computation — pure function of the single-source
GSTR-3B payload (services/returns/pipeline.load_gstr3b_payload), so the
matrix can never disagree with the payload the JSON/xlsx exporters render.

Statutory set-off order (Rule 88A, as amended — deterministic order emitted
as ordered `steps`, including zero-amount rows so tests and the UI can assert
the ORDER itself):

  1. IGST credit  -> IGST liability  (first mandatory use)
  2. IGST credit remainder -> CGST liability
  3. IGST credit remainder -> SGST liability
  4. CGST credit  -> CGST liability  (own head only — CGST credit can never
                                      pay SGST)
  5. SGST credit  -> SGST liability  (own head)
  6. Cess credit  -> Cess liability

Then per-head net cash payable = liability - set-off applied (integer paise).
The PMT-06 challan summary carries the per-head deposit + the GST portal
payment link when net payable > 0, else an explicit zero-payable state.
NO CPIN is ever fabricated: a real CPIN is generated by the GST portal when
the taxpayer creates the challan there (cpin is None + UI copy says so).

Money is integer paise everywhere; no float crosses any boundary.
"""

from __future__ import annotations

from typing import Any, Final

TAX_HEADS: Final[tuple[str, ...]] = ("IGST", "CGST", "SGST", "CESS")

# The GST portal entry point rendered by the challan card. Never a deep link
# into the payment workflow and never a CPIN — those are portal-generated.
GST_PORTAL_URL: Final[str] = "https://www.gst.gov.in/"

CPIN_NOTE: Final[str] = (
    "A CPIN (challan reference) is generated only on the GST portal after you "
    "create and submit the challan there — this preview never invents one."
)

PMT06_NOTE: Final[str] = (
    "PMT-06 (electronic cash ledger) deposit for this period, split by major "
    "head. Create the challan on the GST portal under Services > Payments > "
    "Create Challan."
)

HEADS_ZERO: Final[dict[str, int]] = {
    "IGST": 0,
    "CGST": 0,
    "SGST": 0,
    "CESS": 0,
}


def _zero_heads() -> dict[str, int]:
    """Fresh mutable copy of the zero per-head map."""
    return dict(HEADS_ZERO)


def _to_paise_dict(heads: dict[str, int]) -> dict[str, int]:
    """Per-head ints -> the API's flat ``{igst_paise, ...}`` response shape.

    Same convention as GSTR-1/3B item rows and the HSN summary — flat
    lowercase ``*_paise`` integer keys — so the frontend renders every
    per-head group with one shared component.
    """
    return {
        "igst_paise": heads["IGST"],
        "cgst_paise": heads["CGST"],
        "sgst_paise": heads["SGST"],
        "cess_paise": heads["CESS"],
    }


def _itc_credits(payload: dict[str, Any]) -> dict[str, int]:
    """ITC available (table 4A) — every itc_avl row, per tax head."""
    heads = _zero_heads()
    for row in payload.get("itc_elg", {}).get("itc_avl", []):
        heads["IGST"] += int(row.get("iamt_paise") or 0)
        heads["CGST"] += int(row.get("camt_paise") or 0)
        heads["SGST"] += int(row.get("samt_paise") or 0)
        heads["CESS"] += int(row.get("csamt_paise") or 0)
    return heads


def _liability(payload: dict[str, Any]) -> dict[str, int]:
    """Total GSTR-3B liability per head from the same payload.

    Sums every sup_details bucket plus the intr_latefee / interest / others
    tax tables — all *_paise integer keys, nothing else.
    """
    heads = _zero_heads()
    sources: list[dict[str, Any]] = [*payload.get("sup_details", {}).values()]
    for key in ("intr_latefee", "interest", "others"):
        source = payload.get(key)
        if isinstance(source, dict):
            sources.append(source)
    for entry in sources:
        heads["IGST"] += int(entry.get("iamt_paise") or 0)
        heads["CGST"] += int(entry.get("camt_paise") or 0)
        heads["SGST"] += int(entry.get("samt_paise") or 0)
        heads["CESS"] += int(entry.get("csamt_paise") or 0)
    return heads


def _set_off_steps(credits: dict[str, int], liability: dict[str, int]) -> list[dict[str, Any]]:
    """Apply Rule 88A credit utilisation in statutory order.

    Returns one row per statutory step IN ORDER (zero-amount rows included
    so the order itself is inspectable/testable). Working dicts are mutated
    freely here; they are copies owned by the caller.
    """
    steps: list[dict[str, Any]] = []

    def _use(order: int, from_head: str, to_head: str) -> None:
        amount = min(credits[from_head], liability[to_head])
        credits[from_head] -= amount
        liability[to_head] -= amount
        steps.append(
            {
                "order": order,
                "from_head": from_head,
                "to_head": to_head,
                "amount_paise": amount,
                "credit_after_paise": credits[from_head],
                "liability_after_paise": liability[to_head],
            }
        )

    _use(1, "IGST", "IGST")  # IGST credit first against IGST liability (mandatory)
    _use(2, "IGST", "CGST")  # remainder split across CGST/SGST
    _use(3, "IGST", "SGST")
    _use(4, "CGST", "CGST")  # own-head credits
    _use(5, "SGST", "SGST")
    _use(6, "CESS", "CESS")
    return steps


def compute_rule88a_setoff(
    payload: dict[str, Any],
    *,
    gstin: str,
    fp: str,
) -> dict[str, Any]:
    """Pure Rule 88A computation from a validated GSTR-3B payload.

    Returns the set-off matrix (ordered steps), per-head net cash payable
    and the PMT-06 challan summary — all integer paise.
    """
    credits = _itc_credits(payload)
    liability = _liability(payload)
    original_credits = dict(credits)
    original_liability = dict(liability)

    # Steps mutate the maps in place: what remains in ``liability`` IS the
    # per-head net cash payable; what remains in ``credits`` is leftover ITC.
    steps = _set_off_steps(credits, liability)
    credit_leftover = {head: max(credits[head], 0) for head in TAX_HEADS}

    net_cash = dict(liability)
    total_net = sum(net_cash[head] for head in TAX_HEADS)
    zero_payable = total_net == 0

    # Response shape: per-head groups are the flat {igst_paise, ...} map
    # (matches the rest of the returns API); step rows keep uppercase
    # from_head/to_head (the statutory major-head labels).
    def _p(d: dict[str, int]) -> dict[str, int]:
        return _to_paise_dict(d)

    return {
        "gstin": gstin,
        "fp": fp,
        "itc_credits": _p(original_credits),
        "liability": _p(original_liability),
        "credit_leftover": _p(credit_leftover),
        "matrix": {"steps": steps},
        "net_cash": _p(net_cash),
        "challan": {
            "pmt06_note": PMT06_NOTE,
            "deposit": _p(net_cash),
            "total_net_paise": total_net,
            "zero_payable": zero_payable,
            "portal_url": GST_PORTAL_URL if not zero_payable else None,
            "cpin": None,
            "cpin_note": CPIN_NOTE,
        },
    }
